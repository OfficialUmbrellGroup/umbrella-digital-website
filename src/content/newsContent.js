export function getNewsBySlug(slug) {
  return news.items.find((item) => item.slug === slug);
}

export function getAdjacentNews(slug) {
  const index = news.items.findIndex((item) => item.slug === slug);
  if (index === -1) return { prev: null, next: null };
  return {
    prev: index > 0 ? news.items[index - 1] : null,
    next: index < news.items.length - 1 ? news.items[index + 1] : null,
  };
}
